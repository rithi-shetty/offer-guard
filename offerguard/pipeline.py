"""Run everything end to end and write the results the README and dashboard use.

    python -m offerguard.pipeline            # full run, about 6-8 minutes
    python -m offerguard.pipeline --quick    # smaller run for CI, about 1 minute

Outputs
    reports/results.json     every number quoted in the docs
    reports/figures/*.png    charts used in the README
    web/data.js              carts, model estimates and outcomes for the dashboard
    web/results.js           experiment results for the dashboard's Evidence screen
"""
from __future__ import annotations

import argparse
import json
import time
import warnings
from pathlib import Path

import numpy as np

from . import evaluate as ev
from . import experiments as ex
from . import figures
from .config import BASE, REASONS, SCENARIO_LABELS, Policy

ROOT = Path(__file__).resolve().parent.parent
REPORTS, WEB = ROOT / "reports", ROOT / "web"

warnings.filterwarnings("ignore")


def _clean(o):
    """Make numpy types JSON-friendly and round floats for readable diffs."""
    if isinstance(o, dict):
        return {k: _clean(v) for k, v in o.items()}
    if isinstance(o, (list, tuple)):
        return [_clean(v) for v in o]
    if isinstance(o, (np.integer,)):
        return int(o)
    if isinstance(o, (np.floating, float)):
        return None if not np.isfinite(o) else round(float(o), 4)
    if isinstance(o, np.bool_):
        return bool(o)
    return o


def export_dashboard_data(live, path: Path) -> None:
    """Carts in the compact row format the dashboard reads (same layout as the challenge prototype)."""
    fields = ["id", "sid", "t", "v", "m", "ar", "pa", "po", "pbo", "pf", "im", "tw", "il", "oo",
              "en", "es", "ef", "sn", "ss", "sf", "pur", "seg", "dup", "hk", "act", "rec", "ord"]
    ridx = {r: i for i, r in enumerate(REASONS)}
    rows = []
    for r in live.itertuples(index=False):
        rows.append([r.id, r.sid, r.t, int(r.v), round(float(r.m), 2), ridx[r.reason], int(r.pa), int(r.po),
                     int(r.pbo), int(r.pf), int(r.im), float(r.tw), int(r.il), int(r.oo),
                     round(float(r.en), 3), round(float(r.es), 3), round(float(r.ef), 3),
                     int(r.sn), int(r.ss), int(r.sf), int(r.organic), r.type, int(r.dup), r.hk,
                     int(r.action), int(r.rec), int(r.orders)])
    payload = {"fields": fields, "reasons": list(REASONS), "rows": rows}
    path.write_text("// Generated by offerguard.pipeline. Do not edit by hand.\n"
                    "const RAW = " + json.dumps(payload, separators=(",", ":")) + ";\n", encoding="utf8")


def main(quick: bool = False) -> dict:
    t0 = time.time()
    pool = 8 if quick else 16
    policy = Policy()
    say = lambda msg: print(f"[{time.time() - t0:6.1f}s] {msg}", flush=True)

    say("Simulating comparable brands' randomised learning phases")
    bank = ex.brand_bank(BASE, 15 if quick else 31)
    own = ex.brand_log(BASE, BASE.seed)
    logs = [own] + bank[:pool - 1]

    say("Choosing the model")
    bakeoff = ex.model_bakeoff(logs, policy)

    say("Training the chosen model and running the live phase")
    model = ex.fit(logs, bakeoff["chosen"])
    sim = ex.run_brand(BASE, model, policy)
    live = sim.live_carts()

    say("Scoring strategies")
    table = ev.strategy_table(live, policy)
    results = {
        "meta": {"version": "2.0.0", "quick": quick, "pooled_brands": pool, "train_carts": model.n_train,
                 "model": bakeoff["chosen"], "live_carts": int(len(live)),
                 "carried_out": int(ev.carried_out(live).sum()), "weeks_live": BASE.weeks_live,
                 "policy": policy.__dict__},
        "strategies": table,
        "holdout": ev.holdout_readout(live),
        "calibration": ev.calibration(live),
        "uplift_quintiles": ev.uplift_by_quintile(live),
        "mix": ev.decision_mix(live),
        "by_type": ev.by_hidden_type(live),
        "alerts": sim.alerts,
        "bakeoff": bakeoff,
    }

    say("Learning curve: how many brands' evidence is needed")
    results["learning_curve"] = ex.learning_curve(bank, own, live, sizes=(1, 2, 4, 8) if quick else (1, 2, 4, 8, 16, 32),
                                                  reps=3 if quick else 6, policy=policy, kind=bakeoff["chosen"])
    say("What each signal is worth")
    results["signal_value"] = ex.signal_value(logs, live, policy, kind=bakeoff["chosen"])
    say("The minimum-gain dial")
    results["frontier"] = ex.policy_frontier(live, policy=policy)
    say("Pilot sample size")
    results["pilot"] = ex.pilot_power(live, policy)
    say("Stress tests")
    stress = ex.stress_tests(pool=pool, policy=policy, kind=bakeoff["chosen"])
    for r in stress:
        r["label"] = SCENARIO_LABELS[r["scenario"]]
    results["stress"] = stress
    say("Robustness across fresh worlds")
    results["robustness"] = ex.robustness(seeds=range(5 if quick else 20), pool=pool, bank_size=20 if quick else 40,
                                          policy=policy, kind=bakeoff["chosen"])

    results = _clean(results)
    REPORTS.mkdir(exist_ok=True)
    (REPORTS / "results.json").write_text(json.dumps(results, indent=1), encoding="utf8")
    WEB.mkdir(exist_ok=True)
    export_dashboard_data(live, WEB / "data.js")
    (WEB / "results.js").write_text("// Generated by offerguard.pipeline. Do not edit by hand.\nconst RESULTS = "
                                    + json.dumps(results, separators=(",", ":")) + ";\n", encoding="utf8")
    say("Drawing figures")
    figures.draw_all(results, REPORTS / "figures")
    say("Done")
    return results


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--quick", action="store_true", help="smaller run for CI")
    main(quick=ap.parse_args().quick)
